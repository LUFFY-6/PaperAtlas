export function stylePrompt(style: unknown) {
  return normalizeStyle(style) === 'witty'
    ? '风趣讲解：用自然、简短的比喻或机智例子解释难点，保留术语和证据，不拿研究对象开玩笑。'
    : '务实讲解：直接解释定义、步骤、结果和适用条件，教学例子尽量具体。'
}

